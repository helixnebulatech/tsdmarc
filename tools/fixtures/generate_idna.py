"""Generate packages/tsdmarc/src/utils/idna-data.ts from the `idna` package.

dnspython encodes non-ASCII names with IDNA 2008 (the `idna` package), which
rejects code points that UTS 46 / WHATWG (`node:url`'s `domainToASCII`)
accept, such as emoji and symbols. tsdmarc checks each label against the
same RFC 5892 code point classes, read here from `idna.idnadata`.

Usage: .venv/bin/python -I tools/fixtures/generate_idna.py
"""

from __future__ import annotations

from pathlib import Path

import idna
import idna.idnadata as idnadata

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "packages/tsdmarc/src/utils/idna-data.ts"


def ranges(name: str) -> list[int]:
    flat: list[int] = []
    for packed in idnadata.codepoint_classes[name]:
        flat.extend((packed >> 32, packed & 0xFFFFFFFF))
    return flat


def main() -> None:
    def fmt(values: list[int]) -> str:
        lines = []
        for start in range(0, len(values), 12):
            lines.append("  " + ", ".join(str(v) for v in values[start : start + 12]) + ",")
        return "\n".join(lines)

    OUT.write_text(
        "// Generated by tools/fixtures/generate_idna.py from idna "
        f"{idna.__version__} (Unicode {idnadata.__version__}). Do not edit.\n"
        "//\n"
        "// RFC 5892 code point classes as flat [start, end) pairs.\n\n"
        "/** PVALID code points. */\n"
        f"export const IDNA_PVALID: readonly number[] = [\n{fmt(ranges('PVALID'))}\n];\n\n"
        "/** CONTEXTJ code points (joiners). */\n"
        f"export const IDNA_CONTEXTJ: readonly number[] = [\n{fmt(ranges('CONTEXTJ'))}\n];\n\n"
        "/** CONTEXTO code points. */\n"
        f"export const IDNA_CONTEXTO: readonly number[] = [\n{fmt(ranges('CONTEXTO'))}\n];\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
