const PAGE_SHIFT = 8;
const LOW_BYTE = 0xff;
const WORD_SHIFT = 5;
const BIT_MASK = 0x1f;
const PAGE_WORDS_SHIFT = 3;

// Expat's UCS2_GET_NAMING: the page table picks a 256-bit block of the bitmap.
function lookup(pages: Uint8Array, code: number): boolean {
  const page = pages[code >> PAGE_SHIFT] ?? 0;
  const low = code & LOW_BYTE;
  const word =
    NAMING_BITMAP[(page << PAGE_WORDS_SHIFT) + (low >> WORD_SHIFT)] ?? 0;
  return (word & (1 << (low & BIT_MASK))) !== 0;
}

/** Expat's name-start test for a BMP code point >= 0x80. */
export function isNmstrtCode(code: number): boolean {
  return lookup(NMSTRT_PAGES, code);
}

/** Expat's name-character test for a BMP code point >= 0x80. */
export function isNameCode(code: number): boolean {
  return lookup(NAME_PAGES, code);
}
